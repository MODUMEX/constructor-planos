// src/tarifas.ts
function familiaTarifa(familia) {
  switch (familia) {
    case "PT":
      return "puerta";
    case "PN":
      return "panel";
    case "PL":
      return "pilastra";
    case "MG":
      return "mingitorio";
    default:
      return "antepecho";
  }
}
function anchoCobradoPuerta(anchoCm) {
  return { 62: 70, 64: 70, 92: 100, 94: 100 }[anchoCm] ?? anchoCm;
}
function juegoDeTier(tier) {
  return tier === "especial" ? "especiales" : tier;
}
function precioPieza(pieza, o) {
  const tabla = o.tarifas ?? TARIFAS_BASE;
  const modelo = tabla[o.modeloCodigo] ?? tabla.ESTANDAR;
  if (!modelo) return 0;
  const m2 = (pieza.familia === "PT" ? anchoCobradoPuerta(pieza.anchoCm) : pieza.anchoCm) * pieza.altoCm / 1e4;
  const fam = familiaTarifa(pieza.familia);
  const juego = juegoDeTier(o.tier);
  const leer = (nombre) => {
    const j = modelo[nombre];
    if (!j || typeof j === "boolean") return void 0;
    const v = j[fam];
    return v != null ? v : fam === "antepecho" ? j.puerta : void 0;
  };
  if (modelo.usdOnly) {
    const valido = ["linea", "especiales", "aceroInox", "antigrafiti"].includes(juego);
    const clave2 = valido ? juego : "especiales";
    let usd = leer(clave2) ?? 0;
    if (o.moneda === "CRC") {
      if (clave2 === "linea") usd = leer("lineaCR") ?? usd;
      return m2 * usd * (o.tipoCambio || 0);
    }
    return m2 * usd;
  }
  const claveTier = juego === "linea" ? "linea" : "especiales";
  const clave = o.moneda === "CRC" ? `${claveTier}CRC` : claveTier;
  const tarifa = leer(clave) ?? leer(claveTier) ?? leer("especiales") ?? leer("linea") ?? 0;
  return m2 * tarifa;
}

